#!/usr/bin/env python3
"""Derive docs for the decomposition: verification matrix, TBD register, nested outline, summary.
Run from the repo root after tools/gen_decomp.py."""
import os, re, sys, json, collections
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from sysmlparse import blocks
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
t = open(os.path.join(root, 'models', 'TiltrotorVehicleDecomposition.sysml')).read()
bs = blocks(t)
pk = {}
for m in re.finditer(r"    package (\w+) \{", t): pk[m.start()] = m.group(1)
def pkg(b): return [v for s, v in sorted(pk.items()) if s < b['start']][-1]
esc = lambda s: s.replace('|', '/')
dep = dict((m.group(1), m.group(2)) for m in re.finditer(r"dependency from (\S+) to (\S+);", t))
rows = []
for b in bs:
    a = b['attrs']
    rows.append(dict(id=b['id'], name=b['name'], doc=b['doc'], pkg=pkg(b), parent=b['parent']['id'] if b['parent'] else None,
                     method=(a.get('verifyBy') or '').split('::')[-1], phase=a.get('phase', ''), basis=(a.get('basis') or '').split('::')[-1],
                     why=a.get('rationale', ''), path=b['path'], tbd=len(re.findall(r'\[TBD', b['doc']))))
byid = {r['id']: r for r in rows}
def depth(r):
    d = 1
    while r['parent']: r = byid[r['parent']]; d += 1
    return d
m = ['# Decomposition verification matrix', '', 'Generated by tools/derive_decomp.py from models/TiltrotorVehicleDecomposition.sysml. Do not edit by hand.', '',
     '| ID | Requirement | Method | Phase | Basis | Rationale |', '|---|---|---|---|---|---|']
m += ['| %s | %s | %s | %s | %s | %s |' % (r['id'], esc(r['doc']), r['method'], r['phase'], r['basis'], esc(r['why'])) for r in rows]
tb = ['# Decomposition TBD register', '', 'One row per requirement that carries an open value. Close a row by replacing the [TBD] in tools/decomp and regenerating.', '',
      '| # | ID | Open values | Basis | Needed by | Requirement |', '|---|---|---|---|---|---|']
k = 0
for r in rows:
    if r['tbd']:
        k += 1; tb.append('| %d | %s | %d | %s | %s | %s |' % (k, r['id'], r['tbd'], r['basis'], r['phase'], esc(r['doc'])))
ol = ['# Decomposition outline', '', 'Nested as in the model: each requirement sits under the requirement it refines.', '']
def emit(r):
    ol.append('  ' * (depth(r) - 1) + '- **%s** %s' % (r['id'], r['doc']))
    for c in rows:
        if c['parent'] == r['id']: emit(c)
groups = collections.OrderedDict()
for r in rows: groups.setdefault(r['pkg'], []).append(r)
for g, rs in groups.items():
    ol += ['', '## ' + g, '']
    for r in rs:
        if r['parent'] is None: emit(r)
S = dict(total=len(rows), withTbd=sum(1 for r in rows if r['tbd']), openValues=sum(r['tbd'] for r in rows),
         maxDepth=max(depth(r) for r in rows), byPackage={g: len(v) for g, v in groups.items()},
         byMethod=dict(collections.Counter(r['method'] for r in rows)), byBasis=dict(collections.Counter(r['basis'] for r in rows)),
         byPhase=dict(collections.Counter(r['phase'] for r in rows)))
d = os.path.join(root, 'docs')
open(os.path.join(d, 'decomposition_matrix.md'), 'w').write('\n'.join(m) + '\n')
open(os.path.join(d, 'decomposition_tbd.md'), 'w').write('\n'.join(tb) + '\n')
open(os.path.join(d, 'decomposition_outline.md'), 'w').write('\n'.join(ol) + '\n')
json.dump(S, open(os.path.join(d, 'decomposition_summary.json'), 'w'), indent=1)
print(json.dumps(S))

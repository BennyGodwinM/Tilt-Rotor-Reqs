#!/usr/bin/env python3
"""First sizing pass. Every input in A is an assumption that must be confirmed. Nothing is a measured or vendor value.
Takeoff mass is found by iteration because pack mass depends on takeoff mass.
Writes docs/sizing.md and docs/sizing.json. Run from the repo root: python3 tools/sizing.py"""
import json, math, os, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
A = dict(g=9.81, rho=1.225, rotors=2, diameter_m=0.508, fm=0.65, eta_hover=0.80, eta_cruise_prop=0.70, eta_cruise_motor=0.85,
         ld=10.0, cruise_ms=25.0, takeoff_landing_hover_min=2.0, hover_loiter_min=3.0, mission_min=30.0, avionics_w=30.0,
         reserve_frac=0.20, pack_wh_kg=160.0, tw_peak=1.30, limit_lb=55.0, margin_frac=0.15)
for arg in sys.argv[1:]:
    k, v = arg.split('='); A[k] = float(v)
a = A
FIXED = [('Airframe, wing and fuselage', 5.0, 'assumed'), ('Motors, speed controllers and rotors', 2.6, 'assumed'),
         ('Tilt mechanisms', 0.8, 'assumed'), ('Avionics and radio', 0.6, 'assumed'),
         ('Gimbal and payload sensor', 1.0, 'assumed, heaviest sensor'), ('FPV camera and transmitter', 0.2, 'assumed'),
         ('Landing gear', 0.6, 'assumed'), ('Wiring and connectors', 0.6, 'assumed')]
hover_min = a['takeoff_landing_hover_min'] + a['hover_loiter_min']
cruise_min = a['mission_min'] - hover_min
def powers(m):
    W = m * a['g']; T = W / a['rotors']; Ad = math.pi * (a['diameter_m'] / 2) ** 2
    Ph = a['rotors'] * T ** 1.5 / math.sqrt(2 * a['rho'] * Ad) / a['fm'] / a['eta_hover']
    Pc = (W / a['ld']) * a['cruise_ms'] / (a['eta_cruise_prop'] * a['eta_cruise_motor'])
    return Ph, Pc
def pack(m):
    Ph, Pc = powers(m)
    return (Ph * hover_min / 60 + Pc * cruise_min / 60 + a['avionics_w'] * a['mission_min'] / 60) / (1 - a['reserve_frac']) / a['pack_wh_kg']
fixed = sum(i[1] for i in FIXED)
m = 20.0; it = []
for _ in range(200):
    mb = pack(m); mn = (fixed + mb) * (1 + a['margin_frac']); it.append((m, mb, mn))
    if abs(mn - m) < 0.005: break
    m = mn
M = round(m, 2)
L = []
def p(s=''): L.append(s)
def line(name, expr, val, unit): p(f'| {name} | {expr} | {val} {unit} |')
p('# First sizing pass'); p()
p('Generated by tools/sizing.py. Every input below is an **assumption** to confirm or replace; none is a measured or vendor value. Change an input with `python3 tools/sizing.py name=value` and rerun.'); p()
p('## Assumed inputs'); p(); p('| Input | Value |'); p('|---|---|')
for k, v in A.items(): p(f'| {k} | {v} |')
p(); p('## Takeoff mass iteration'); p()
p('Pack mass depends on takeoff mass, and takeoff mass depends on pack mass, so the mass is iterated until the budget with margin equals the takeoff mass.'); p()
p('| Step | Takeoff mass in (kg) | Pack mass (kg) | Budget with margin out (kg) |'); p('|---|---|---|---|')
for k, (x, y, z) in enumerate(it, 1): p(f'| {k} | {x:.2f} | {y:.2f} | {z:.2f} |')
p(); p(f'Converged takeoff mass: **{M} kg** after {len(it)} steps.'); p()
p('## Steps at the converged mass'); p(); p('| Quantity | Working | Result |'); p('|---|---|---|')
W = M * a['g']; line('Weight', f"W = m g = {M} x {a['g']}", f'{W:.1f}', 'N')
T = W / a['rotors']; line('Thrust per rotor in hover', f"T = W / {a['rotors']:.0f} = {W:.1f} / {a['rotors']:.0f}", f'{T:.2f}', 'N')
Ad = math.pi * (a['diameter_m'] / 2) ** 2; line('Disk area per rotor', f"A = pi (D/2)^2 = pi x {a['diameter_m']/2:.2f}^2", f'{Ad:.4f}', 'm2')
DL = T / Ad; line('Disk loading', f"DL = T / A = {T:.2f} / {Ad:.4f}", f'{DL:.0f}', 'N/m2')
den = math.sqrt(2 * a['rho'] * Ad); line('Denominator', f"sqrt(2 rho A) = sqrt(2 x {a['rho']} x {Ad:.4f})", f'{den:.4f}', '')
Pid = T ** 1.5 / den; line('Ideal power per rotor', f"T^1.5 / sqrt(2 rho A) = {T**1.5:.1f} / {den:.4f}", f'{Pid:.0f}', 'W')
Pid2 = Pid * a['rotors']; line('Ideal power, both rotors', f"{Pid:.0f} x {a['rotors']:.0f}", f'{Pid2:.0f}', 'W')
Psh = Pid2 / a['fm']; line('Shaft power', f"{Pid2:.0f} / FM = {Pid2:.0f} / {a['fm']}", f'{Psh:.0f}', 'W')
Ph = Psh / a['eta_hover']; line('Electrical hover power', f"{Psh:.0f} / {a['eta_hover']}", f'{Ph:.0f}', 'W')
D = W / a['ld']; line('Cruise drag', f"D = W / (L/D) = {W:.1f} / {a['ld']}", f'{D:.1f}', 'N')
Pa = D * a['cruise_ms']; line('Aerodynamic power', f"D V = {D:.1f} x {a['cruise_ms']}", f'{Pa:.0f}', 'W')
ec = a['eta_cruise_prop'] * a['eta_cruise_motor']; line('Cruise efficiency', f"{a['eta_cruise_prop']} x {a['eta_cruise_motor']}", f'{ec:.3f}', '')
Pc = Pa / ec; line('Electrical cruise power', f"{Pa:.0f} / {ec:.3f}", f'{Pc:.0f}', 'W')
Eh = Ph * hover_min / 60; line('Hover energy', f"{Ph:.0f} x {hover_min:.0f} / 60", f'{Eh:.1f}', 'Wh')
Ecr = Pc * cruise_min / 60; line('Cruise energy', f"{Pc:.0f} x {cruise_min:.0f} / 60", f'{Ecr:.1f}', 'Wh')
Ea = a['avionics_w'] * a['mission_min'] / 60; line('Avionics and payload energy', f"{a['avionics_w']:.0f} x {a['mission_min']:.0f} / 60", f'{Ea:.1f}', 'Wh')
Em = Eh + Ecr + Ea; line('Mission energy', f"{Eh:.1f} + {Ecr:.1f} + {Ea:.1f}", f'{Em:.1f}', 'Wh')
Eu = Em / (1 - a['reserve_frac']); line('Pack usable energy with reserve', f"{Em:.1f} / (1 - {a['reserve_frac']}) = {Em:.1f} / {1-a['reserve_frac']:.2f}", f'{Eu:.0f}', 'Wh')
mb = Eu / a['pack_wh_kg']; line('Pack mass', f"{Eu:.0f} / {a['pack_wh_kg']:.0f}", f'{mb:.2f}', 'kg')
Ppk = Ph * a['tw_peak'] ** 1.5; line('Peak electrical power', f"P_hover x (T/W)^1.5 = {Ph:.0f} x {a['tw_peak']}^1.5", f'{Ppk:.0f}', 'W')
C = Ppk / Eu; line('Peak discharge rate', f"{Ppk:.0f} / {Eu:.0f} (per hour)", f'{C:.1f}', 'C')
lim = a['limit_lb'] * 0.45359237; line('Part 107 mass limit', f"{a['limit_lb']:.0f} lb x 0.45359237", f'{lim:.2f}', 'kg')
mg = 1 - M / lim; line('Margin of takeoff mass below the limit', f"1 - {M} / {lim:.2f}", f'{mg*100:.0f}', 'percent')
p(); p('## Mass budget'); p(); p('| Item | Mass (kg) | Basis |'); p('|---|---|---|')
p(f'| Battery pack | {mb:.2f} | from sizing |')
for n, mm, b in FIXED: p(f'| {n} | {mm} | {b} |')
tot = fixed + mb; p(f'| **Sum** | {tot:.2f} | |'); p(f"| **Sum with {a['margin_frac']*100:.0f} percent margin** | {tot*(1+a['margin_frac']):.2f} | {tot:.2f} x {1+a['margin_frac']} |")
p(); p('## What the pass shows'); p()
p(f"- Hover decides the power: {Ph:.0f} W in hover against {Pc:.0f} W in cruise, so {Eh/Em*100:.0f} percent of mission energy goes to {hover_min:.0f} of {a['mission_min']:.0f} minutes.")
p(f"- Each minute of hover costs {Ph/60:.0f} Wh; each minute of cruise costs {Pc/60:.0f} Wh.")
p(f"- Peak discharge is {C:.1f} C, so the pack needs a high-rate cell; {a['pack_wh_kg']:.0f} Wh/kg is the assumed pack-level specific energy.")
p(f"- The takeoff mass is {mg*100:.0f} percent below the Part 107 limit of {lim:.2f} kg.")
open(os.path.join(root, 'docs', 'sizing.md'), 'w').write('\n'.join(L) + '\n')
R_ = dict(inputs=A, hoverMin=hover_min, cruiseMin=cruise_min, mtow=M, W=W, T=T, DL=DL, Ph=Ph, Pc=Pc, Eh=Eh, Ecr=Ecr, Em=Em, Eu=Eu, pack=mb, Ppk=Ppk, C=C, limit=lim, margin=mg)
json.dump(R_, open(os.path.join(root, 'docs', 'sizing.json'), 'w'), indent=1)
print(json.dumps({k: round(v, 2) for k, v in R_.items() if k != 'inputs'}))

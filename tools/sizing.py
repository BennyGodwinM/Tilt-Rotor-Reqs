#!/usr/bin/env python3
"""First sizing pass in US customary units. Every input in A is an assumption to confirm; none is a measured or vendor value.
Takeoff weight is found by iteration because pack weight depends on takeoff weight.
Mass in lb is treated as weight in lbf (standard gravity). Power is computed in ft-lbf/s and shown in W (1 ft-lbf/s = 1.35582 W).
Writes docs/sizing.md and docs/sizing.json. Run from the repo root: python3 tools/sizing.py [name=value ...]"""
import json, math, os, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
A = dict(rho_slug_ft3=0.002377, rotors=2, diameter_in=20.0, fm=0.65, eta_hover=0.80, eta_cruise_prop=0.70, eta_cruise_motor=0.85,
         ld=10.0, cruise_kt=48.6, takeoff_landing_hover_min=2.0, hover_loiter_min=3.0, mission_min=30.0, avionics_w=30.0,
         reserve_frac=0.20, pack_wh_lb=72.6, tw_peak=1.30, limit_lb=55.0, margin_frac=0.15)
for arg in sys.argv[1:]:
    k, v = arg.split('='); A[k] = float(v)
a = A
FTLBF_S_TO_W = 1.35582
KT_TO_FTS = 1.68781
FIXED = [('Airframe, wing and fuselage', 11.0, 'assumed'), ('Motors, speed controllers and rotors', 5.7, 'assumed'),
         ('Tilt mechanisms', 1.8, 'assumed'), ('Avionics and radio', 1.3, 'assumed'),
         ('Gimbal and payload sensor', 2.2, 'assumed, heaviest sensor'), ('FPV camera and transmitter', 0.4, 'assumed'),
         ('Landing gear', 1.3, 'assumed'), ('Wiring and connectors', 1.3, 'assumed')]
hover_min = a['takeoff_landing_hover_min'] + a['hover_loiter_min']
cruise_min = a['mission_min'] - hover_min
V = a['cruise_kt'] * KT_TO_FTS
Ad = math.pi * (a['diameter_in'] / 12 / 2) ** 2
def powers(w):
    T = w / a['rotors']
    Ph = a['rotors'] * T ** 1.5 / math.sqrt(2 * a['rho_slug_ft3'] * Ad) / a['fm'] / a['eta_hover'] * FTLBF_S_TO_W
    Pc = (w / a['ld']) * V / (a['eta_cruise_prop'] * a['eta_cruise_motor']) * FTLBF_S_TO_W
    return Ph, Pc
def pack(w):
    Ph, Pc = powers(w)
    return (Ph * hover_min / 60 + Pc * cruise_min / 60 + a['avionics_w'] * a['mission_min'] / 60) / (1 - a['reserve_frac']) / a['pack_wh_lb']
fixed = sum(i[1] for i in FIXED)
w = 45.0; it = []
for _ in range(300):
    pb = pack(w); wn = (fixed + pb) * (1 + a['margin_frac']); it.append((w, pb, wn))
    if abs(wn - w) < 0.01: break
    w = wn
M = round(w, 1)
L = []
def p(s=''): L.append(s)
def line(name, expr, val, unit): p(f'| {name} | {expr} | {val} {unit} |')
p('# First sizing pass'); p()
p('Generated by tools/sizing.py. Every input below is an **assumption** to confirm or replace; none is a measured or vendor value. All quantities are in US customary units; power is shown in watts (electrical convention). Change an input with `python3 tools/sizing.py name=value` and rerun.'); p()
p('## Assumed inputs'); p(); p('| Input | Value |'); p('|---|---|')
for k, v in A.items(): p(f'| {k} | {v} |')
p(); p('## Takeoff weight iteration'); p()
p('Pack weight depends on takeoff weight, and takeoff weight depends on pack weight, so the weight is iterated until the budget with margin equals the takeoff weight.'); p()
p('| Step | Takeoff weight in (lb) | Pack weight (lb) | Budget with margin out (lb) |'); p('|---|---|---|---|')
for k, (x, y, z) in enumerate(it, 1): p(f'| {k} | {x:.2f} | {y:.2f} | {z:.2f} |')
p(); p(f'Converged takeoff weight: **{M} lb** after {len(it)} steps.'); p()
p('## Steps at the converged weight'); p(); p('| Quantity | Working | Result |'); p('|---|---|---|')
W = M; line('Weight', f"W = {M} lb of mass at standard gravity", f'{W:.1f}', 'lbf')
T = W / a['rotors']; line('Thrust per rotor in hover', f"T = W / {a['rotors']:.0f} = {W:.1f} / {a['rotors']:.0f}", f'{T:.2f}', 'lbf')
R = a['diameter_in'] / 12 / 2; line('Rotor radius', f"R = D / 2 = {a['diameter_in']:.0f} in / 12 / 2", f'{R:.4f}', 'ft')
line('Disk area per rotor', f"A = pi R^2 = pi x {R:.4f}^2", f'{Ad:.4f}', 'ft2')
DL = T / Ad; line('Disk loading', f"DL = T / A = {T:.2f} / {Ad:.4f}", f'{DL:.1f}', 'lbf/ft2')
den = math.sqrt(2 * a['rho_slug_ft3'] * Ad); line('Denominator', f"sqrt(2 rho A) = sqrt(2 x {a['rho_slug_ft3']} x {Ad:.4f})", f'{den:.4f}', '')
Pid = T ** 1.5 / den; line('Ideal power per rotor', f"T^1.5 / sqrt(2 rho A) = {T**1.5:.1f} / {den:.4f}", f'{Pid:.0f}', 'ft-lbf/s')
Pid2 = Pid * a['rotors']; line('Ideal power, both rotors', f"{Pid:.0f} x {a['rotors']:.0f}", f'{Pid2:.0f}', 'ft-lbf/s')
Psh = Pid2 / a['fm']; line('Shaft power', f"{Pid2:.0f} / FM = {Pid2:.0f} / {a['fm']}", f'{Psh:.0f}', 'ft-lbf/s')
Pel = Psh / a['eta_hover']; line('Electrical hover power', f"{Psh:.0f} / {a['eta_hover']}", f'{Pel:.0f}', 'ft-lbf/s')
Ph = Pel * FTLBF_S_TO_W; line('Electrical hover power in watts', f"{Pel:.0f} x {FTLBF_S_TO_W}", f'{Ph:.0f}', 'W')
D = W / a['ld']; line('Cruise drag', f"D = W / (L/D) = {W:.1f} / {a['ld']}", f'{D:.2f}', 'lbf')
line('Cruise speed', f"{a['cruise_kt']} kt x {KT_TO_FTS}", f'{V:.1f}', 'ft/s')
Pa = D * V; line('Aerodynamic power', f"D V = {D:.2f} x {V:.1f}", f'{Pa:.0f}', 'ft-lbf/s')
ec = a['eta_cruise_prop'] * a['eta_cruise_motor']; line('Cruise efficiency', f"{a['eta_cruise_prop']} x {a['eta_cruise_motor']}", f'{ec:.3f}', '')
Pc = Pa / ec * FTLBF_S_TO_W; line('Electrical cruise power in watts', f"{Pa:.0f} / {ec:.3f} x {FTLBF_S_TO_W}", f'{Pc:.0f}', 'W')
Eh = Ph * hover_min / 60; line('Hover energy', f"{Ph:.0f} x {hover_min:.0f} / 60", f'{Eh:.1f}', 'Wh')
Ecr = Pc * cruise_min / 60; line('Cruise energy', f"{Pc:.0f} x {cruise_min:.0f} / 60", f'{Ecr:.1f}', 'Wh')
Ea = a['avionics_w'] * a['mission_min'] / 60; line('Avionics and payload energy', f"{a['avionics_w']:.0f} x {a['mission_min']:.0f} / 60", f'{Ea:.1f}', 'Wh')
Em = Eh + Ecr + Ea; line('Mission energy', f"{Eh:.1f} + {Ecr:.1f} + {Ea:.1f}", f'{Em:.1f}', 'Wh')
Eu = Em / (1 - a['reserve_frac']); line('Pack usable energy with reserve', f"{Em:.1f} / (1 - {a['reserve_frac']}) = {Em:.1f} / {1-a['reserve_frac']:.2f}", f'{Eu:.0f}', 'Wh')
mb = Eu / a['pack_wh_lb']; line('Pack weight', f"{Eu:.0f} / {a['pack_wh_lb']}", f'{mb:.2f}', 'lb')
Ppk = Ph * a['tw_peak'] ** 1.5; line('Peak electrical power', f"P_hover x (T/W)^1.5 = {Ph:.0f} x {a['tw_peak']}^1.5", f'{Ppk:.0f}', 'W')
C = Ppk / Eu; line('Peak discharge rate', f"{Ppk:.0f} / {Eu:.0f} (per hour)", f'{C:.1f}', 'C')
lim = a['limit_lb']; line('Part 107 weight limit', "14 CFR 107.3, 55 lb", f'{lim:.0f}', 'lb')
mg = 1 - M / lim; line('Margin of takeoff weight below the limit', f"1 - {M} / {lim:.0f}", f'{mg*100:.0f}', 'percent')
p(); p('## Weight budget'); p(); p('| Item | Weight (lb) | Basis |'); p('|---|---|---|')
p(f'| Battery pack | {mb:.2f} | from sizing |')
for n, m_, b in FIXED: p(f'| {n} | {m_} | {b} |')
tot = fixed + mb; p(f'| **Sum** | {tot:.2f} | |'); p(f"| **Sum with {a['margin_frac']*100:.0f} percent margin** | {tot*(1+a['margin_frac']):.2f} | {tot:.2f} x {1+a['margin_frac']} |")
p(); p('## What the pass shows'); p()
p(f"- Hover decides the power: {Ph:.0f} W in hover against {Pc:.0f} W in cruise, so {Eh/Em*100:.0f} percent of mission energy goes to {hover_min:.0f} of {a['mission_min']:.0f} minutes.")
p(f"- Each minute of hover costs {Ph/60:.0f} Wh; each minute of cruise costs {Pc/60:.0f} Wh.")
p(f"- Peak discharge is {C:.1f} C, so the pack needs a high-rate cell; {a['pack_wh_lb']:.1f} Wh/lb is the assumed pack-level specific energy.")
p(f"- The takeoff weight is {mg*100:.0f} percent below the Part 107 limit of {lim:.0f} lb.")
open(os.path.join(root, 'docs', 'sizing.md'), 'w').write('\n'.join(L) + '\n')
R_ = dict(inputs=A, hoverMin=hover_min, cruiseMin=cruise_min, mtowLb=M, T=T, DL=DL, Ph=Ph, Pc=Pc, Eh=Eh, Ecr=Ecr, Em=Em, Eu=Eu, packLb=mb, Ppk=Ppk, C=C, limitLb=lim, margin=mg)
json.dump(R_, open(os.path.join(root, 'docs', 'sizing.json'), 'w'), indent=1)
print(json.dumps({k: round(v, 2) for k, v in R_.items() if k != 'inputs'}))

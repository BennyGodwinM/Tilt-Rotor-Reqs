#!/usr/bin/env python3
"""First sizing pass. Every input marked A is an assumption chosen by the chief engineer's agent and must be confirmed.
Writes docs/sizing.md and docs/sizing.json. Run from the repo root."""
import json, math, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
A = dict(  # assumptions
 mtow_kg=20.0, g=9.81, rho=1.225, rotors=2, diameter_m=0.76, fm=0.65, eta_hover=0.80, eta_cruise_prop=0.70, eta_cruise_motor=0.85,
 ld=10.0, cruise_ms=25.0, hover_min=2.0, mission_min=30.0, avionics_w=30.0, reserve_frac=0.20, pack_wh_kg=160.0, tw_peak=1.30,
 limit_lb=55.0, margin_frac=0.15)
a = A; L = []
def p(s=''): L.append(s)
def line(name, expr, val, unit): p(f'| {name} | {expr} | {val} {unit} |')
p('# First sizing pass'); p()
p('Generated by tools/sizing.py. Every input below is an **assumption** to be confirmed or replaced; none is a measured or vendor value. Change the inputs in the script and rerun.'); p()
p('## Assumed inputs'); p(); p('| Input | Value |'); p('|---|---|')
for k, v in A.items(): p(f'| {k} | {v} |')
p(); p('## Steps'); p(); p('| Quantity | Working | Result |'); p('|---|---|---|')
W = a['mtow_kg']*a['g']; line('Weight', f"W = m g = {a['mtow_kg']} x {a['g']}", f'{W:.1f}', 'N')
T = W/a['rotors']; line('Thrust per rotor in hover', f"T = W / {a['rotors']} = {W:.1f} / {a['rotors']}", f'{T:.2f}', 'N')
R = a['diameter_m']/2; Ad = math.pi*R**2; line('Disk area per rotor', f"A = pi (D/2)^2 = pi x {R:.2f}^2", f'{Ad:.4f}', 'm2')
DL = T/Ad; line('Disk loading', f"DL = T / A = {T:.2f} / {Ad:.4f}", f'{DL:.0f}', 'N/m2')
den = math.sqrt(2*a['rho']*Ad); line('Denominator', f"sqrt(2 rho A) = sqrt(2 x {a['rho']} x {Ad:.4f})", f'{den:.4f}', '')
Pid = T**1.5/den; line('Ideal power per rotor', f"P = T^1.5 / sqrt(2 rho A) = {T**1.5:.1f} / {den:.4f}", f'{Pid:.0f}', 'W')
Pid2 = Pid*a['rotors']; line('Ideal power, both rotors', f"{Pid:.0f} x {a['rotors']}", f'{Pid2:.0f}', 'W')
Psh = Pid2/a['fm']; line('Shaft power', f"P / FM = {Pid2:.0f} / {a['fm']}", f'{Psh:.0f}', 'W')
Ph = Psh/a['eta_hover']; line('Electrical hover power', f"P_shaft / eta = {Psh:.0f} / {a['eta_hover']}", f'{Ph:.0f}', 'W')
D = W/a['ld']; line('Cruise drag', f"D = W / (L/D) = {W:.1f} / {a['ld']}", f'{D:.1f}', 'N')
Pa = D*a['cruise_ms']; line('Aerodynamic power', f"D V = {D:.1f} x {a['cruise_ms']}", f'{Pa:.0f}', 'W')
ec = a['eta_cruise_prop']*a['eta_cruise_motor']; line('Cruise efficiency', f"{a['eta_cruise_prop']} x {a['eta_cruise_motor']}", f'{ec:.3f}', '')
Pc = Pa/ec + a['avionics_w']*0; line('Electrical cruise power (propulsion)', f"{Pa:.0f} / {ec:.3f}", f'{Pc:.0f}', 'W')
th = a['hover_min']; tc = a['mission_min']-th
Eh = Ph*th/60; line('Hover energy', f"{Ph:.0f} x {th} / 60", f'{Eh:.1f}', 'Wh')
Ecr = Pc*tc/60; line('Cruise energy', f"{Pc:.0f} x {tc} / 60", f'{Ecr:.1f}', 'Wh')
Ea = a['avionics_w']*a['mission_min']/60; line('Avionics and payload energy', f"{a['avionics_w']} x {a['mission_min']} / 60", f'{Ea:.1f}', 'Wh')
Em = Eh+Ecr+Ea; line('Mission energy', f"{Eh:.1f} + {Ecr:.1f} + {Ea:.1f}", f'{Em:.1f}', 'Wh')
Eu = Em/(1-a['reserve_frac']); line('Pack usable energy with reserve', f"E / (1 - {a['reserve_frac']}) = {Em:.1f} / {1-a['reserve_frac']:.2f}", f'{Eu:.0f}', 'Wh')
mb = Eu/a['pack_wh_kg']; line('Pack mass', f"E / specific energy = {Eu:.0f} / {a['pack_wh_kg']}", f'{mb:.2f}', 'kg')
Ppk = Ph*a['tw_peak']**1.5; line('Peak electrical power', f"P_hover x T/W^1.5 = {Ph:.0f} x {a['tw_peak']}^1.5", f'{Ppk:.0f}', 'W')
C = Ppk/Eu; line('Peak discharge rate', f"P_peak / E = {Ppk:.0f} / {Eu:.0f}", f'{C:.1f}', 'C')
lim = a['limit_lb']*0.45359237; line('Part 107 mass limit', f"{a['limit_lb']} lb x 0.45359237", f'{lim:.2f}', 'kg')
mg = 1-a['mtow_kg']/lim; line('Margin of target MTOW below the limit', f"1 - {a['mtow_kg']} / {lim:.2f}", f'{mg*100:.0f}', 'percent')
p(); p('## First mass budget'); p(); p('| Item | Mass (kg) | Basis |'); p('|---|---|---|')
items=[('Airframe, wing and fuselage',5.0,'assumed'),('Battery pack',round(mb,2),'from sizing'),('Motors, speed controllers and rotors',2.6,'assumed'),('Tilt mechanisms',0.8,'assumed'),('Avionics and radio',0.6,'assumed'),('Gimbal and payload sensor',1.0,'assumed, heaviest sensor'),('FPV camera and transmitter',0.2,'assumed'),('Landing gear',0.6,'assumed'),('Wiring and connectors',0.6,'assumed')]
tot=sum(i[1] for i in items)
for n,m,b in items: p(f'| {n} | {m} | {b} |')
mm=tot*(1+a['margin_frac']); p(f'| **Sum** | {tot:.2f} | |'); p(f"| **Sum with {a['margin_frac']*100:.0f} percent margin** | {mm:.2f} | {tot:.2f} x {1+a['margin_frac']} |")
p(); p(f"The budget with margin ({mm:.2f} kg) is {'below' if mm<a['mtow_kg'] else 'ABOVE'} the {a['mtow_kg']} kg target by {abs(a['mtow_kg']-mm):.2f} kg.")
p(); p('## What the pass shows'); p()
p(f"- Hover decides the power: {Ph:.0f} W in hover against {Pc:.0f} W in cruise, so {Eh/Em*100:.0f} percent of mission energy goes to {th:.0f} minutes of hover.")
p(f"- The pack is limited by power as much as by energy: a {C:.1f} C peak discharge needs a high-rate pack, which is why the assumed pack specific energy is as low as {a['pack_wh_kg']:.0f} Wh/kg.")
p(f"- Longer hover time costs {Ph/60:.0f} Wh per minute; C/VTOL and VTOL missions with long hovers will not meet 30 minutes without a bigger pack.")
open(os.path.join(root,'docs','sizing.md'),'w').write('\n'.join(L)+'\n')
R_=dict(W=W,T=T,DL=DL,Ph=Ph,Pc=Pc,Eh=Eh,Ecr=Ecr,Em=Em,Eu=Eu,mb=mb,Ppk=Ppk,C=C,mass=mm,margin=mg)
json.dump(R_,open(os.path.join(root,'docs','sizing.json'),'w'),indent=1)
print(json.dumps({k:round(v,2) for k,v in R_.items()}))

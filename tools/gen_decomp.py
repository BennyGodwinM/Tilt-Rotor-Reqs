"""Generate models/TiltrotorVehicleDecomposition.sysml and docs/checklists.md from tools/decomp/*."""
import csv, glob, os
D = os.path.dirname(os.path.abspath(__file__)); R = os.path.dirname(D)
VEH = {'VEH-1':'configuration','VEH-2':'endurance','VEH-3':'part107','VEH-3.1':'part107::maxMass','VEH-3.2':'part107::envelope',
       'VEH-3.3':'part107::lineOfSight','VEH-4':'conversion','VEH-5':'whirlFlutterFree','VEH-6':'strength',
       'VEH-7':'modeLogic','VEH-8':'boundaryComplete'}
GROUPS = [('pwr','PowerReqs'),('prop','PropulsionReqs'),('tilt','TiltReqs'),('payload','PayloadReqs'),
          ('stab','StabilityReqs'),('ops','OperationsReqs'),
          ('fcs','ControlReqs'),('aero','AeroReqs'),('str','StructureReqs'),('avn','AvionicsReqs'),('swr','SoftwareReqs')]
VM = {'T':'byTest','A':'byAnalysis','D':'byDemonstration','I':'byInspection'}
rows = []
for f, pk in GROUPS:
    for l in open(os.path.join(D, 'decomp', f + '.txt')):
        if l.strip() and not l.startswith('#'):
            i, par, nm, tx, v, ph, b, ra = l.rstrip('\n').split('|')
            rows.append(dict(id=i, parent=par, name=nm, text=tx, v=v, ph=ph, b=b, ra=ra, pk=pk))
q = {i: 'TiltrotorVehicleRequirements::vehicleReqs::' + n for i, n in VEH.items()}
for r in rows: q[r['id']] = r['pk'] + '::' + r['name']
ids = {r['id'] for r in rows}
for r in rows:
    assert r['parent'] in q, (r['id'], r['parent'])
    assert '*/' not in r['text']
    assert r['name'].isidentifier(), r['name']
esc = lambda s: s.replace('\\', '\\\\').replace('"', '\\"')
o = ['package TiltrotorVehicleDecomposition {', '    private import ScalarValues::*;',
     '    private import TiltrotorVehicleRequirements::*;', '',
     '    // Generated by tools/gen_decomp.py from tools/decomp/*.txt. Edit the .txt files, not this file.', '']
for f, pk in GROUPS:
    o.append('    package %s {' % pk)
    for r in [x for x in rows if x['pk'] == pk]:
        o += ["        requirement <'%s'> %s : VehicleRequirement {" % (r['id'], r['name']),
              '            doc /* %s */' % r['text'],
              '            attribute :>> basis = Basis::%s;' % r['b'],
              '            attribute :>> rationale = "%s";' % esc(r['ra']),
              '            attribute :>> phase = "%s";' % r['ph'],
              '            attribute :>> verifyBy = VerificationMethod::%s;' % VM[r['v']], '        }']
    o += ['    }', '']
o.append('    // Derivation: each requirement depends on the parent it refines')
for r in rows:
    o.append('    dependency from %s to %s;' % (q[r['id']], q[r['parent']]))
o += ['', '    // Allocation of new requirements to the design']
for a, b in (('OPS-005','tiltrotor::landingGear'),('FPV-001','tiltrotor::fpvCamera'),('PLD-001','tiltrotor::noseGimbal::payloadSensor'),('STB-001','tiltrotor::flightController'),('AVN-001','tiltrotor::radioLink')):
    o.append('    satisfy %s by TiltrotorVehicleRequirements::%s;' % (q[a], b))
o.append('}')
open(os.path.join(R, 'models', 'TiltrotorVehicleDecomposition.sysml'), 'w').write('\n'.join(o) + '\n')
ck = list(csv.DictReader(open(os.path.join(D, 'decomp', 'checklists.csv'))))
for c in ck:
    for t in c['traces'].split(';'): assert t in q, (c['item'], t)
m = ['# Preflight and postflight checklists', '',
     'Generated from `tools/decomp/checklists.csv`. Every item traces to a requirement. Items marked All apply to every mode; a flight uses the All items plus the items for its mode (C/VTOL uses the CTOL and VTOL items that apply to the planned modes).', '']
for ph, title in (('Pre', 'Preflight'), ('Post', 'Postflight')):
    for md in ('All', 'CTOL', 'VTOL', 'C/VTOL'):
        it = [c for c in ck if c['phase'] == ph and c['mode'] == md]
        if not it: continue
        m += ['## %s: %s' % (title, md), '', '| Done | Item | Check | Traces to |', '|---|---|---|---|']
        m += ['| [ ] | %s | %s | %s |' % (c['item'], c['check'], ', '.join(c['traces'].split(';'))) for c in it] + ['']
open(os.path.join(R, 'docs', 'checklists.md'), 'w').write('\n'.join(m))
print(len(rows), 'requirements,', len(ck), 'checklist items')

#!/usr/bin/env python3
"""Derive the Armstrong chapters 3 and 4, the verification matrix and the TBD register from the two models.
Run from the repo root: python3 tools/derive.py   Add --check to fail instead of writing."""
import re,sys,os
ORDER=['SE','AER','LDS','STR','SIN','ROT','FLU','FTP','SOF','CMG']
GROUP={'SE':'seReqs','AER':'aerodynamicsReqs','LDS':'loadsReqs','STR':'structuresReqs','SIN':'structuralIntegrityReqs','ROT':'rotorEffectsReqs','FLU':'flutterReqs','FTP':'flightTestReqs','SOF':'safetyOfFlightReqs','CMG':'configurationManagementReqs'}
def blocks(t):
    """Parse nested requirement usages into a flat list of dicts with path, doc, attrs."""
    out=[];stack=[]  # (name,depth)
    pat=re.compile(r"requirement <'([\w.-]+)'> (\w+) : \w+ \{")
    i=0
    for m in pat.finditer(t):
        # find matching close brace
        d=1;j=m.end()
        while d:
            c=t[j]; d+= (c=='{')-(c=='}'); j+=1
        body=t[m.end():j-1]
        head=re.sub(r"requirement <.*",'',body,flags=re.S) # text before first nested requirement
        doc=re.search(r"doc /\* (.*?) \*/",head,re.S).group(1).strip()
        attrs={}
        for a in re.finditer(r"attribute (?::>> )?(\w+)(?: *: *\w+)?(?: *= *(?:\"([^\"]*)\"|(\w+::\w+)|([-\d.eE]+)))?;",head):
            attrs[a.group(1)]=a.group(2) or a.group(3) or a.group(4)
        out.append(dict(id=m.group(1),name=m.group(2),start=m.start(),end=j,doc=doc,attrs=attrs))
    for b in out:
        b['parent']=None
        for c in out:
            if c is not b and c['start']<b['start']<c['end'] and (b['parent'] is None or c['start']>b['parent']['start']): b['parent']=c
    for b in out:
        path=[];c=b
        while c: path.append(c['name']);c=c['parent']
        b['path']='::'.join(reversed(path))
    return out
def num(i): return [int(x) if x.isdigit() else x for x in re.split(r'[-.]',i)[1:]]
root=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rd=lambda f:open(os.path.join(root,'models',f)).read()
prog=blocks(rd('TiltrotorProgramModel.sysml'));veh=blocks(rd('TiltrotorVehicleRequirements.sysml'))
pt,vt=rd('TiltrotorProgramModel.sysml'),rd('TiltrotorVehicleRequirements.sysml')
ids=[b['id'] for b in prog+veh];dups={i for i in ids if ids.count(i)>1}
if dups: sys.exit(f'duplicate ids {dups}')
# paragraph numbers
aliases=[];para={}
vkids=lambda p:sorted([b for b in veh if b['parent'] is p],key=lambda b:num(b['id']))
vroot=[b for b in veh if b['parent'] is None][0]
def walk(b,pre):
    for k,c in enumerate(vkids(b),1):
        n=f'{pre}.{k}' if pre else f'3.{k}';para[c['id']]=n
        aliases.append(('3',f"        alias <'{n}'> {c['name']}Req for TiltrotorVehicleRequirements::{c['path']};"));walk(c,n)
walk(vroot,'')
proot=[b for b in prog if b['parent'] is None][0]
for gi,pfx in enumerate(ORDER,1):
    g=[b for b in prog if b['name']==GROUP[pfx]][0];n=f'4.{gi}';para[g['id']]=n
    aliases.append(('4',f"        alias <'{n}'> {g['name'][:-4]}Para for TiltrotorProgramModel::{g['path']};"))
    for k,c in enumerate(sorted([b for b in prog if b['parent'] is g],key=lambda b:num(b['id'])),1):
        m=f'{n}.{k}';para[c['id']]=m
        aliases.append(('4',f"        alias <'{m}'> {c['name']}Req for TiltrotorProgramModel::{c['path']};"))
def chapter(ch,name):
    return f"    package {name} {{\n"+"\n".join(a for c,a in aliases if c==ch)+"\n    }\n"
af=os.path.join(root,'models','AFRC_TiltrotorRequirementsDocument.sysml');at=open(af).read()
for ch,name in (('3','Chapter3_VehicleRequirements'),('4','Chapter4_ProgramRequirements')):
    at=re.sub(r"    package %s \{.*?\n    \}\n"%name,lambda m:chapter(ch,name),at,flags=re.S)
leaf=[b for b in prog if not b['id'].endswith('-0') and b['id']!='PRG-0']
rows=[]
for b in sorted(leaf,key=lambda b:(ORDER.index(b['id'].split('-')[0]),num(b['id']))):
    a=b['attrs'];rows.append((para[b['id']],b['id'],b['doc'],a.get('owner','').split('::')[-1],a.get('milestone','').split('::')[-1],a.get('basis','').split('::')[-1],a.get('source','')))
vrows=[]
for b in veh:
    if b['id']=='VEH-0':continue
    a=b['attrs'];vrows.append((para[b['id']],b['id'],b['doc'],a.get('verifyBy','').split('::')[-1],a.get('basis','').split('::')[-1],a.get('successCriteria',''),a.get('facility',''),a.get('phase','')))
vrows.sort(key=lambda r:[int(x) for x in r[0].split('.')])
esc=lambda s:s.replace('|','/')
mx=["# Verification matrix (Appendix C)","","Generated by tools/derive.py from the models. Do not edit by hand.","","## Vehicle requirements","","| Para | ID | Requirement | Success criteria | Method | Facility | Phase | Basis |","|---|---|---|---|---|---|---|---|"]
mx+=[f"| {p} | {i} | {esc(d)} | {esc(c)} | {m} | {f} | {ph} | {b} |" for p,i,d,m,b,c,f,ph in vrows]
mx+=["","## Program requirements","","| Para | ID | Requirement | Success criteria | Method | Phase | Owner | Basis | Source |","|---|---|---|---|---|---|---|---|---|"]
mx+=[f"| {p} | {i} | {esc(d)} | Deliverable released and accepted at {ms} | byInspection | {ms} | {o} | {b} | {s} |" for p,i,d,o,ms,b,s in rows]
# TBD register
tbd=[]
for b in prog+veh:
    if b['id'] in('PRG-0','VEH-0'):continue
    a=b['attrs'];bs=a.get('basis','').split('::')[-1];ms=a.get('milestone','SRR').split('::')[-1]
    if bs=='placeholder': tbd.append((b['id'],'basis is placeholder',b['doc'][:110],'Chief engineer',ms))
    for k,v in a.items():
        if v and re.fullmatch(r'[-\d.eE]+',v) and k not in('rangeMin','rangeMax') and bs!='directive':
            tbd.append((b['id'],f'starting value {k} = {v} ('+bs+')','confirm or replace','Chief engineer',ms))
    if re.search(r'to be (set|defined|named)|TBD',b['doc']): tbd.append((b['id'],'text defers a value','"'+re.search(r'[^.]*(to be (?:set|defined|named)|TBD)[^.]*',b['doc']).group(0).strip()+'"','Chief engineer',ms))
for m in re.finditer(r"attribute (\w+) : BoundaryVariable \{(.*?)\}",vt):
    for need in('latencyMs','tolerance'):
        if need not in m.group(2): tbd.append(('VEH-8',f'boundary variable {m.group(1)} has no {need}','set before PDR','Chief engineer','PDR'))
for m in re.finditer(r'attribute :>> (\w+) = "TBD"',at): tbd.append(('Cover',f'{m.group(1)} is TBD','assign at baseline','Configuration manager','SRR'))
if 'Holder to be named' in at: tbd.append(('Ch.2','approving authority holder not named','name in the CMP','Project manager','SRR'))
tb=["# TBD register","","Generated by tools/derive.py. A row is closed by editing the model value or its basis.","","| # | Item | Open point | Detail | Decision owner | Needed by |","|---|---|---|---|---|---|"]
tb+=[f"| {k} | {i} | {w} | {esc(d)} | {o} | {m} |" for k,(i,w,d,o,m) in enumerate(tbd,1)]
BAD=r"\b(flexible|easy|easily|sufficient|safe|ad hoc|adequate|accommodate|user-friendly|usable|when required|if required|appropriate|fast|portable|light-weight|small|large|maximi[sz]e|minimi[sz]e|robust|quickly|clearly|[a-z]+ly)\b"
OKLY={'only','early','apply','family','assembly','daily','likely','supply','fly','reply','Assembly','simply','Probably','Hardly','relatively'}
lint=[]
for b in prog+veh:
    if b['id'] in('PRG-0','VEH-0') or b['id'].endswith('-0'):continue
    hits=sorted({w for w in re.findall(BAD,b['doc'],re.I) if w.lower() not in OKLY and not w.lower().endswith(('ally',)) or w.lower() in('easily','quickly','clearly')})
    if hits: lint.append((b['id'],', '.join(hits)))
    if len(re.findall(r"\bshall\b",b['doc']))!=1 and not re.search(r"\bshall\b.*\bshall\b",b['doc']) and 'shall' not in b['doc']: lint.append((b['id'],'no shall'))
trace=[b['id'] for b in veh if b['id']!='VEH-0' and ('dependency from vehicleReqs::'+b['name']+' ' not in vt and 'dependency from vehicleReqs::'+b['name']+' ' not in vt) and not (b['parent'] and b['parent']['id']!='VEH-0' and ('vehicleReqs::'+b['parent']['name']+' ') in ''.join(re.findall(r"dependency from .*",vt)))]
lr=["# Requirement lint report","","Generated by tools/derive.py. Terms from the NASA SE Handbook Appendix C list of unverifiable words, plus any -ly word, are flagged for a person to judge; a hit is not automatically wrong.","","| ID | Flagged |","|---|---|"]+[f"| {i} | {w} |" for i,w in lint]+["","## Vehicle requirements with no trace to a program requirement","",", ".join(trace) or "None"]
if '--check' in sys.argv: print('ok', len(leaf),'program',len(vrows),'vehicle',len(tbd),'tbd');sys.exit()
open(af,'w').write(at)
os.makedirs(os.path.join(root,'docs'),exist_ok=True)
open(os.path.join(root,'docs','verification_matrix.md'),'w').write("\n".join(mx)+"\n")
open(os.path.join(root,'docs','lint_report.md'),'w').write("\n".join(lr)+"\n")
open(os.path.join(root,'docs','tbd_register.md'),'w').write("\n".join(tb)+"\n")
print(len(leaf),'program',len(vrows),'vehicle requirements;',len(aliases),'aliases;',len(tbd),'TBD rows')
